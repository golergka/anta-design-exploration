import { test, expect } from '@playwright/test'
test('validation, controlled input, reset, focus, thread and narrow layout', async ({ page }) => {
 await page.goto('/')
 await page.getByRole('button',{name:'Send',exact:true}).click()
 await expect(page.getByText('Write a message first')).toBeVisible()
 const input=page.locator('textarea')
 await expect(input).toBeFocused()
 await input.fill('Hello team')
 await page.getByRole('button',{name:'Send',exact:true}).click()
 await expect(page.getByText('Hello team')).toBeVisible()
 await expect(input).toHaveValue('')
 await expect(input).toBeFocused()
 await page.getByRole('button',{name:'3 replies'}).click()
 await expect(page.getByRole('heading',{name:'Thread'})).toBeVisible()
 await page.setViewportSize({width:390,height:700})
 await page.getByRole('button',{name:'Close thread'}).click()
 await expect(input).toBeVisible()
 await input.focus()
 await input.evaluate(el=>el.dispatchEvent(new CompositionEvent('compositionstart',{bubbles:true,data:''})))
 await page.keyboard.insertText('日本語')
 await page.keyboard.press('Enter')
 await input.evaluate(el=>el.dispatchEvent(new CompositionEvent('compositionend',{bubbles:true,data:'日本語'})))
 await expect(input).toHaveValue('日本語\n')
 await expect(page.locator('.messages').getByText('日本語')).toHaveCount(0)
 await page.getByRole('button',{name:'Send',exact:true}).click()
 await expect(input).toHaveValue('')
 await expect(page.locator('.messages').getByText('日本語')).toBeVisible()
})
